// частые продукты для демо-вкладки «Часто используемые» — генерируется по usage-счётчику в store, оставим как подмножество favorite
export function makeRecipeTotals(r: Recipe): {
  kcal: number;
  protein: number;
  fat: number;
  carbs: number;
} {
  const t = r.ingredients.reduce(
    (acc, i) => ({
      kcal: acc.kcal + i.kcal,
      protein: acc.protein + i.protein,
      fat: acc.fat + i.fat,
      carbs: acc.carbs + i.carbs,
    }),
    { kcal: 0, protein: 0, fat: 0, carbs: 0 }
  );
  return {
    kcal: Math.round(t.kcal / r.servingsCount),
    protein: Math.round(t.protein / r.servingsCount),
    fat: Math.round(t.fat / r.servingsCount),
    carbs: Math.round(t.carbs / r.servingsCount),
  };
}

